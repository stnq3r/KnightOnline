SELECT TOP 10 nOriginItem FROM ITEM_UPGRADE WHERE nOriginItem>0 AND nOriginItem NOT IN (SELECT Num FROM ITEM);
SELECT 'UPG_BACKUP distinct old-only' k, COUNT(DISTINCT nOriginItem) v FROM ITEM_UPGRADE WHERE nOriginItem>0 AND nOriginItem NOT IN (SELECT Num FROM ITEM_BAK_20261015);
